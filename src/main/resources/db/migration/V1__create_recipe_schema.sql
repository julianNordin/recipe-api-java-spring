-- Initial schema. Flyway owns this; Hibernate runs with ddl-auto=validate and never writes DDL,
-- so every column here has to line up with the @Column mapping or startup fails.

CREATE TABLE recipes (
    id           BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(200)  NOT NULL,
    description  VARCHAR(1000),
    instructions VARCHAR(5000) NOT NULL,
    prep_minutes INTEGER       NOT NULL,
    cook_minutes INTEGER       NOT NULL,
    servings     INTEGER       NOT NULL,
    difficulty   VARCHAR(20)   NOT NULL,
    created_at   TIMESTAMPTZ   NOT NULL,
    updated_at   TIMESTAMPTZ   NOT NULL
);

CREATE TABLE ingredients (
    id   BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL
);

-- The real uniqueness rule for ingredients, and the reason there is no plain UNIQUE (name):
-- "Flour" and "flour" are the same ingredient. A functional unique index is the only way to say
-- that in Postgres, and it implies uniqueness of name anyway.
CREATE UNIQUE INDEX ux_ingredients_name_lower ON ingredients (lower(name));

CREATE TABLE categories (
    id   BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(60) NOT NULL,
    CONSTRAINT ux_categories_name UNIQUE (name)
);

CREATE TABLE recipe_ingredients (
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id     BIGINT        NOT NULL,
    ingredient_id BIGINT        NOT NULL,
    quantity      NUMERIC(10, 2) NOT NULL,
    unit          VARCHAR(20)   NOT NULL,

    CONSTRAINT fk_recipe_ingredients_recipe
        FOREIGN KEY (recipe_id) REFERENCES recipes (id) ON DELETE CASCADE,

    -- No ON DELETE CASCADE here on purpose. Deleting an ingredient that a recipe still uses
    -- must fail, so the API can answer 409 rather than silently gutting recipes (Phase 15).
    CONSTRAINT fk_recipe_ingredients_ingredient
        FOREIGN KEY (ingredient_id) REFERENCES ingredients (id),

    -- One line per ingredient per recipe. Backs the "same ingredient twice" rule in Phase 08.
    CONSTRAINT ux_recipe_ingredients_recipe_ingredient UNIQUE (recipe_id, ingredient_id)
);

CREATE TABLE recipe_categories (
    recipe_id   BIGINT NOT NULL,
    category_id BIGINT NOT NULL,

    -- Composite primary key: the pairing is the identity, there is nothing else to store.
    CONSTRAINT pk_recipe_categories PRIMARY KEY (recipe_id, category_id),

    CONSTRAINT fk_recipe_categories_recipe
        FOREIGN KEY (recipe_id) REFERENCES recipes (id) ON DELETE CASCADE,
    CONSTRAINT fk_recipe_categories_category
        FOREIGN KEY (category_id) REFERENCES categories (id) ON DELETE CASCADE
);

-- Postgres indexes the leading column of a composite key/constraint but not the trailing one.
-- These cover the reverse lookups: "which recipes use this ingredient" (the 409 check) and
-- "which recipes are in this category" (the category filter).
CREATE INDEX ix_recipe_ingredients_ingredient ON recipe_ingredients (ingredient_id);
CREATE INDEX ix_recipe_categories_category ON recipe_categories (category_id);
